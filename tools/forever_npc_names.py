"""Writes Data/ForeverNpcNames.lua: names for mobs Forever added.

Run from the repository root before a release, with the owner's account
save (SavedVariables/Blackthornes_Farmer.lua):

    python tools/forever_npc_names.py <save>

Inside a dungeon the game hides every mob's name from addons, and a mob
Forever added is in no list, so the kills panel shows "Creature #250484".
A player names it with a right-click ("Name this mob"), and Farmer also
keeps a name whenever the game shows one; both land in the save's
npcNames. This reads only npcNames, keeps the IDs Data/NpcNames.lua does
not already name, and adds them to what this file already ships. A name
already shipped is never changed here.

A name is kept only when it is plain text the addon itself would keep
(Harvest.CleanName): one line, no colour codes, not a number, at most 60
characters, and nothing the clear-to-post scan refuses.

Never edit the output by hand; rerun this.
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_package import PRIVATE  # noqa: E402

OUT = Path("Data/ForeverNpcNames.lua")
CLASSIC = Path("Data/NpcNames.lua")
NAME_MOST = 60
ENTRY = re.compile(r'\[(\d+)\]\s*=\s*"((?:[^"\\]|\\.)*)"')


def unescape(text):
    return re.sub(r"\\(.)", r"\1", text)


def clean(text):
    text = re.sub(r"[\x00-\x1f]", " ", text.replace("|", ""))
    text = re.sub(r"\s+", " ", text).strip()
    if not text or text.startswith("Creature #") or text.isdigit() or len(text) > NAME_MOST:
        return None
    if any(pattern.search(text) for _, pattern in PRIVATE):
        return None
    return text


def block(text, key):
    """The body of the table saved under ["key"] = { ... }, or ""."""
    start = text.find('["%s"] = {' % key)
    if start < 0:
        return ""
    depth, i = 0, text.index("{", start)
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1:j]
    return ""


def read(path):
    if not path.exists():
        return {}
    return {int(k): unescape(v) for k, v in ENTRY.findall(path.read_text(encoding="utf-8"))}


def lua_string(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def build(save_text, classic, shipped):
    names = dict(shipped)
    for npc, raw in ENTRY.findall(block(save_text, "npcNames")):
        npc = int(npc)
        if npc in classic or npc in names:
            continue
        name = clean(unescape(raw))
        if name:
            names[npc] = name
    return names


def write(names):
    out = [
        "-- Blackthornes Farmer -- Data/ForeverNpcNames.lua",
        "-- Generated by tools/forever_npc_names.py; never edit by hand. Names for",
        "-- mobs Forever added that the game will not name inside a dungeon, as",
        "-- players named them in game (\"Name this mob\" in the kills panel).",
        "",
        "local _, ns = ...",
        "",
        "ns.FOREVER_NPC_NAMES = {",
    ]
    out += ['    [%d] = "%s",' % (npc, lua_string(names[npc])) for npc in sorted(names)]
    out += ["}", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    save_text = Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace")
    shipped = read(OUT)
    names = build(save_text, read(CLASSIC), shipped)
    write(names)
    print("%s: %d names (%d new)" % (OUT, len(names), len(names) - len(shipped)))


if __name__ == "__main__":
    main()
