"""Writes Data/Data_Rares.lua: Forever's rare mobs and treasure chests.

Run from the repository root:

    python tools/make_rares.py <rare list> <Classic data> <Forever tables folder>

  rare list               a JSON file with `rares` (mob ID, map spots by
                          map ID, the items it can drop) and `treasures`
                          (object ID, map spots, the items inside)
  Classic data            Classic 1.12's spawns and names, the same folder
                          tools/make_known_drops.py reads
  Forever tables folder   the Forever client's game tables as CSV: Item.csv,
                          ItemSparse.csv and Creature.csv

For the Grind tab's Rares and Treasures views, their map pins and the search.
Only rares and chests with a name and a spot on a zone map we know are
written. No drop rates: the list names items, not how often they drop.

A rare's levels come from our own looted rows for its name, else Classic's.
Each item a rare drops also gets a `searchOnly` row, so the search names the
rare; a looted row or any other row for that mob in that zone wins.

Never edit the output by hand; rerun this.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_package import PRIVATE  # noqa: E402
from make_classic_drops import NAME, lua_string  # noqa: E402
from make_known_drops import (  # noqa: E402
    classic_units, item_names, looted_spots, mob_names, unescape, zone_tables)

OUT = Path("Data/Data_Rares.lua")
MAX_SPOTS = 12
MAX_ITEMS = 8


def private(name):
    return any(p.search(name) for _, p in PRIVATE)


def spots_of(coords, by_id):
    """[(map ID, zone, x, y)] on zone maps we know, at most MAX_SPOTS."""
    out = []
    for map_id, points in (coords or {}).items():
        map_id = int(map_id)
        if map_id not in by_id:
            continue
        for point in points or []:
            if len(point) < 2:
                continue
            x, y = float(point[0]), float(point[1])
            if 0 < x < 100 and 0 < y < 100:
                out.append((map_id, by_id[map_id], round(x, 1), round(y, 1)))
    return out[:MAX_SPOTS]


def levels(name, mob, looted, units):
    for _, _, _, low, high in looted.get(name, []):
        return low, high
    if mob in units:
        return units[mob][1], units[mob][2]
    return None


def lua_spots(spots):
    return "{ %s }" % ", ".join("{ %d, %.1f, %.1f }" % (m, x, y) for m, _, x, y in spots)


def lua_ids(ids):
    return "{ %s }" % ", ".join(str(i) for i in ids) if ids else "{}"


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    classic, tables = Path(sys.argv[2]) / "db", Path(sys.argv[3])

    by_id, _ = zone_tables()
    items = item_names(tables, classic)
    mobs = mob_names(classic, tables)
    units = classic_units(classic)
    looted = looted_spots()
    objects = {int(i): unescape(n) for i, n in NAME.findall(
        (classic / "enUS" / "objects.lua").read_text(encoding="utf-8"))}

    def named_items(ids):
        out = []
        for item in ids or []:
            if item in items and item not in out and not private(items[item][0]):
                out.append(item)
        return out[:MAX_ITEMS]

    rares, used = [], set()
    for row in data.get("rares", []):
        mob = int(row["id"])
        name = mobs.get(mob)
        if not name or name.startswith("[") or private(name):
            continue
        spots = spots_of(row.get("coords"), by_id)
        if not spots:
            continue
        drops = named_items(row.get("drops"))
        used.update(drops)
        rares.append((name, mob, spots, levels(name, mob, looted, units), drops,
                      len(row.get("drops") or []) > len(drops)))

    treasures = []
    for row in data.get("treasures", []):
        thing = int(row["id"])
        spots = spots_of(row.get("coords"), by_id)
        if not spots:
            continue
        contents = named_items(row.get("items"))
        name = objects.get(thing)
        if not name or private(name):
            name = None
        if not name and not contents:
            continue
        used.update(contents)
        treasures.append((name, thing, spots, contents))

    out = [
        "-- Blackthornes Farmer -- Data/Data_Rares.lua",
        "-- Generated by tools/make_rares.py; never edit by hand. Forever's rare",
        "-- mobs and treasure chests with their spots (map ID, x, y) and what",
        "-- they can give, with no drop rates.",
        "",
        "local _, ns = ...",
        "",
        "local DB = ns.DB",
        "",
        "ns.RareData = {",
        "    -- { mob ID, name, low, high, spots, drops, more }: `more` when it",
        "    -- also drops items with no English name.",
        "    rares = {",
    ]
    for name, mob, spots, lv, drops, more in sorted(rares, key=lambda r: (r[2][0][1], r[0], r[1])):
        low, high = lv or (0, 0)
        out.append("        { %d, %s, %d, %d, %s, %s%s }," % (
            mob, lua_string(name), low, high, lua_spots(spots), lua_ids(drops), ", true" if more else ""))
    out += [
        "    },",
        "    -- { object ID, name or false, spots, items }",
        "    treasures = {",
    ]
    for name, thing, spots, contents in sorted(treasures, key=lambda r: (r[2][0][1], r[0] or "", r[1])):
        out.append("        { %d, %s, %s, %s }," % (
            thing, lua_string(name) if name else "false", lua_spots(spots), lua_ids(contents)))
    out += [
        "    },",
        "    -- English item names, for a client that has not seen the item yet.",
        "    items = {",
    ]
    for item in sorted(used):
        out.append("        [%d] = %s," % (item, lua_string(items[item][0])))
    out += ["    },", "}", ""]

    # Search leads: each item a rare drops names the rare, one row a zone.
    leads = 0
    by_item = {}
    for name, mob, spots, lv, drops, _ in rares:
        if not lv:
            continue
        for item in drops:
            for map_id, zone, x, y in spots:
                rows = by_item.setdefault(item, [])
                if not any(r[0] == name and r[1] == zone for r in rows):
                    rows.append((name, zone, x, y, lv[0], lv[1]))
    for item in sorted(by_item, key=lambda i: (items[i][0], i)):
        name, category = items[item]
        kind = "category = %s, " % lua_string(category) if category else ""
        out.append("DB:RegisterItem({ name = %s, id = %d, %ssources = {" % (lua_string(name), item, kind))
        for mob, zone, x, y, low, high in sorted(by_item[item], key=lambda r: (r[4], r[0], r[1])):
            out.append("    { name = %s, zone = %s, coords = { %.1f, %.1f }, minLevel = %d, maxLevel = %d, "
                       "searchOnly = true, rare = true }," % (lua_string(mob), lua_string(zone), x, y, low, high))
            leads += 1
        out.append("} })")
    out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("%s: %d rares, %d treasures, %d items, %d search rows" % (
        OUT, len(rares), len(treasures), len(used), leads))


if __name__ == "__main__":
    main()
