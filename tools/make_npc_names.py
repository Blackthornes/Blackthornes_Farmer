"""Writes Data/NpcNames.lua: the names of Classic's dungeon and raid mobs.

Run from the repository root with pfQuest checked out somewhere:

    python tools/make_npc_names.py <pfQuest>

  github.com/shagu/pfQuest   db/units.lua and db/enUS/units.lua

Inside a dungeon the game hides a corpse's name from addons, and the loot
window gives only the mob's ID (see Harvest:Corpse). This file names those
IDs. It keeps every mob pfQuest has no world spawn for, which is the mobs
inside dungeons and raids (and a few that are never spawned at all). A name
the game itself gives wins over this file, and a mob Forever added is not in
it; those are kept as "Creature #ID" until a name is known.

Never edit the output by hand; rerun this.
"""

import re
import sys
from pathlib import Path

OUT = Path("Data/NpcNames.lua")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    db = Path(sys.argv[1]) / "db"

    units = (db / "units.lua").read_text(encoding="utf-8")
    names = dict(
        (int(npc), name)
        for npc, name in re.findall(r'\[(\d+)\] = "((?:[^"\\]|\\.)*)"',
                                    (db / "enUS" / "units.lua").read_text(encoding="utf-8")))

    unspawned = [
        int(npc) for npc, body in re.findall(r"\n  \[(\d+)\] = \{\n(.*?)\n  \},", units, re.S)
        if '["coords"] = {},' in body
    ]

    # "[UNUSED] ..." and the like are test and cut mobs, never met.
    rows = [(npc, names[npc]) for npc in sorted(unspawned)
            if names.get(npc) and not names[npc].startswith("[")]

    out = [
        "-- Blackthornes Farmer -- Data/NpcNames.lua",
        "-- Generated by tools/make_npc_names.py from pfQuest's database; never edit",
        "-- by hand. The names of mobs with no world spawn: those inside dungeons and",
        "-- raids, whose loot window gives only their ID.",
        "",
        "local _, ns = ...",
        "",
        "ns.NPC_NAMES = {",
    ]
    out += ['    [%d] = "%s",' % (npc, name) for npc, name in rows]
    out += ["}", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("%s: %d names" % (OUT, len(rows)))


if __name__ == "__main__":
    main()
